#!/usr/bin/env python3
"""Generate the Latent Kick realtime instrument (dsp.lisp) + decoder_layout.json (+ optional
random placeholder weights). Voice = kick_np.render(mode="full"); layout = kick_layout.

    python3 gen_dsp.py [--out DIR] --random-weights [--seed 7] [--layout PATH]   (default DIR: $MODAL_AD_ROOT/kick/Latent Kick)

Structure:
  * a D->128->128->P tanh MLP decoder (plain matmul; needs a DGenLisp with dgen 69f392b,
    e.g. this checkout's via ModalSnareAD/scripts/make_dgenlisp_tool.sh) that runs ONLY on
    the onset frame of a hit ((event-hold x hit) inputs);
  * post-decoder per-hit math on the event clock: VILLAIN Kick's transform knobs
    (tune, drop_time, tilt, spread, beat, decay, bend, attack, body, knock, tick), native
    velocity curves and note tracking (note = 2 pitch/440 latched at the hit);
  * per sample: VILLAIN's closed-form 24-slot bank (drop law with 2 drops on slots 0-3 + time
    warp), 5 transient sines, growl, burst, body shaper/saturator, bark, 18 Hz body HP,
    18 unit-RMS band noises + hum on ONE xorshift white, recording clipper, DC blocker,
    record LP, drive split, fade, out gate.
Env: LATENT_TAP=1 adds research outputs (3 modal, 4 noise) for parity.
"""
