def random_weights(seed):
    """placeholder weights: small random W1/W2/W3 around b3 = the mean teacher row (if available)"""
    import numpy as np
    rng = np.random.default_rng(seed)
    D, H, P = L.D_IN, L.H, L.P
    W1 = rng.normal(0, 1 / math.sqrt(D), (D, H)) * 1.2
    W2 = rng.normal(0, 1 / math.sqrt(H), (H, H)) * 1.2
    W3 = rng.normal(0, 1 / math.sqrt(H), (H, P)) * 0.3
    b1 = rng.normal(0, 0.1, (1, H)); b2 = rng.normal(0, 0.1, (1, H))
    tpath = os.path.join(KICK, "data", "teacher.json")
    if os.path.exists(tpath):
        rows = json.load(open(tpath))["rows"]
        U = np.array([r["u"] for k, r in rows.items() if k.startswith("kick_")])
        b3 = U.mean(0, keepdims=True)
    else:
        b3 = np.zeros((1, P))
    return {"l1.W": W1, "l1.b": b1, "l2.W": W2, "l2.b": b2, "l3.W": W3, "l3.b": b3}


def write_weights(params, outdir):
    for name, (f, shp) in WEIGHT_FILES.items():
        a = params[name]
        assert list(a.shape) == shp, (name, a.shape, shp)
        json.dump({"shape": shp, "data": [round(float(x), 7) for x in a.reshape(-1)]}, open(os.path.join(outdir, f), "w"))


def norms_table():
    cache = os.path.join(KICK, ".band_norms.json")
    key = f"{L.BAND_LO}|{L.BAND_HI}|{L.BAND_Q}|{L.BAND_STAGES}|{L.NB}"
    c = json.load(open(cache)) if os.path.exists(cache) else {}
    if c.get("key") != key:
        c = {"key": key, "norms": {str(sr): [KN.band_norm(f, sr) for f in L.BAND_FC] for sr in NORM_RATES}}
        json.dump(c, open(cache, "w"))
    return {float(k): v for k, v in c["norms"].items()}


