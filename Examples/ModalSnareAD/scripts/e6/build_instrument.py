#!/usr/bin/env python3
"""E6 Latent Snare: Snare A / Snare B / Blend on the trained latent, z1..z4 offsets on top.

    python3 build_instrument.py RUN WARP.json DEST

- weights: RUN (trainer space) re-expressed in the E2 knob space (export_instrument.py's PCA
  transform of the codes; the codes are E2's, so knob values and presets carry over);
- dsp.lisp: e7/Latent Snare/dsp.lisp (E2 gen_dsp output + E5 wire_block(2)) with
  * note tracking (pitch / C4 latched at the hit; C4 = training pitch exact),
  * the z inputs replaced by, at the hit (event clock only, no per-sample cost):
        a, b = round(snare_a), round(snare_b);  t = blend;  tau = warp[a,b](t) (or t when even = 0)
        z_i = clip((1 - tau) CODE[a,i] + tau CODE[b,i] + z_i offset, -3, 3)
    CODE [32x4] and the per-pair perceptual arc-length warp [1024x11] compiled in as constants;
- ui.lisp: the E4 latent map panel (drag mode) + SNARES (A/B) + BLEND; data/family.json envelopes from
  the trained voice with wires (e7lib twin);
- instrument.json plain {"version":1,"run_mode":"instrument"}."""
import json, os, re, shutil, sys
import numpy as np
import os, sys  # noqa: E401
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import modal_ad as MAD  # noqa: E402
HERE = MAD.stage("e6"); R = MAD.ROOT
MAD.use("e6")
import common as C

run, warp_path, dest = sys.argv[1:4]
W, Z, names = C.load_run(run)
mu, M, Zk = C.knob_transform(Z)          # z_raw = mu + z_knob @ M
D = Z.shape[1]
# knob-space weights: x_raw = mu + x_k M  ->  W1z' = M W1z, b1' = b1 + mu W1z
W1 = W["l1.W"]; W1z, w1v = W1[:D], W1[D:]
Wn = dict(W); Wn["l1.W"] = np.vstack([M @ W1z, w1v]); Wn["l1.b"] = W["l1.b"] + mu @ W1z
for i in (0, 9, 30):
    a = C.ln.decode_np(W, Z[i], 0.7); b = C.ln.decode_np(Wn, Zk[i], 0.7)
    assert np.abs(a - b).max() < 1e-6 * max(1, np.abs(a).max())
# the E2 instrument's knob codes must be these (presets/panels interchangeable)
e2std = json.load(open(os.path.join(R, "e2/Latent Snare/codes_std.json")))
assert np.abs(np.array([e2std["codes"][n] for n in names]) - Zk).max() < 1e-4
warp = json.load(open(warp_path)); T = np.array(warp["table"])  # [32,32,11]
NK = T.shape[2]

if os.path.exists(dest): shutil.rmtree(dest)
os.makedirs(os.path.join(dest, "data"))
src = os.path.join(R, "e7", "Latent Snare")
for f in ("decoder_layout.json",):
    shutil.copy(os.path.join(src, f), dest)
files = {"l1.W": "w1.json", "l1.b": "b1.json", "l2.W": "w2.json", "l2.b": "b2.json", "l3.W": "w3.json", "l3.b": "b3.json"}
for k, f in files.items():
    a = Wn[k]; json.dump({"shape": list(a.shape), "data": [round(float(x), 8) for x in a.reshape(-1)]}, open(os.path.join(dest, f), "w"))
json.dump({"version": 1, "run_mode": "instrument"}, open(os.path.join(dest, "instrument.json"), "w"))
json.dump({"D": D, "codes": {n: [round(float(x), 5) for x in Zk[i]] for i, n in enumerate(names)}, "order": names,
           "knob_range": [-3, 3], "transform": e2std["transform"], "mu": mu.tolist(), "M": M.tolist(),
           "source_run": os.path.relpath(os.path.abspath(run), C.R), "warp": os.path.relpath(os.path.abspath(warp_path), C.R)},
          open(os.path.join(dest, "codes_std.json"), "w"), indent=1)

# ---- dsp.lisp ----------------------------------------------------------------------------------
dsp = open(os.path.join(src, "dsp.lisp")).read()


def sub(old, new, count=1):
    global dsp
    assert dsp.count(old) == count, (old, dsp.count(old))
    dsp = dsp.replace(old, new)


def colmajor(a):  # (peek T row col) reads data[col * rows + row]
    return " ".join(f"{v:.6g}" for v in np.asarray(a).T.reshape(-1))


sub(";; Latent Modal Snare + E5 W2 snare wires (E7) -- GENERATED: e2 gen_dsp.py output spliced by scripts/e7/build_instrument.py",
    ";; Latent Snare A/B (E6) -- GENERATED by scripts/e6/build_instrument.py from e7/Latent Snare (E2 gen_dsp.py + E5 wire_block(2)).\n"
    ";; Snare A, Snare B, Blend = the straight line z = (1-tau) z_A + tau z_B in the decoder's latent space, tau =\n"
    ";; a per-pair perceptual arc-length warp of blend (even = 1) so equal blend steps sound like equal steps;\n"
    ";; z1..z4 are offsets on top (knob units). Decoder weights: E6 path fine-tune (exact at the 32 snares).")
z_params = "\n".join(f"(param z{i} @default 0 @min -3 @max 3 @mod true @mod-mode additive)" for i in range(1, 5))
sub(z_params, "(param snare_a @default 0 @min 0 @max 31)\n(param snare_b @default 0 @min 0 @max 31)\n"

    "(param blend @default 0 @min 0 @max 1 @mod true @mod-mode additive)\n"
    "(param even @default 1 @min 0 @max 1)\n" + z_params)
holds = "\n".join(f"(def e-z{i} (event-hold (clip (mod z{i}) -3 3) hit))" for i in range(1, 5))
rows = 32 * 32
Tflat = T.reshape(rows, NK)
hats = " ".join(f"(* (peek LS-WARP e-row {k}) (max 0 (- 1 (abs (- e-x {k})))))" for k in range(NK))
new = f""";; snare codes (knob space) [32 x 4] and the per-pair blend warp [32*32 x {NK}] (row = a*32 + b,
;; knot k = tau at blend k/{NK - 1}); both read only on the hit clock.
(def LS-CODE (tensor @shape [32 4] @data [{colmajor(Zk)}]))
(def LS-WARP (tensor @shape [{rows} {NK}] @data [{colmajor(Tflat)}]))
(def e-a (event-hold (floor (+ (clip snare_a 0 31) 0.5)) hit))
(def e-b (event-hold (floor (+ (clip snare_b 0 31) 0.5)) hit))
(def e-t (event-hold (clip (mod blend) 0 1) hit))
(def e-even (event-hold (clip even 0 1) hit))
(def e-row (+ (* e-a 32) e-b))
(def e-x (* e-t {NK - 1}))
(def e-tw (+ {hats}))
(def e-tau (+ e-t (* e-even (- e-tw e-t))))
""" + "\n".join(f"(def e-z{i} (event-hold (clip (+ (* (- 1 e-tau) (peek LS-CODE e-a {i - 1})) (* e-tau (peek LS-CODE e-b {i - 1})) (mod z{i})) -3 3) hit))"
                for i in range(1, 5))
sub(holds, new)
sub("(def e-ratio (exp (* e-tune 0.057762265046662105)))",
    ";; note tracking: trained at C4 (261.6256 Hz), so C4 is exact; like VILLAIN, clipped to +-2 octaves\n"
    "(def e-note (event-hold (clip (/ pitch 261.6255653) 0.25 4) hit))\n"
    "(def e-ratio (* e-note (exp (* e-tune 0.057762265046662105))))")
sub("(def e-vel (event-hold (clip velocity 0 1) hit))", "(def e-vel (event-hold (clip velocity 0.4 1) hit))")
sub("(def voice-out (* (+ shaped carry) level))",
    ";; Velocity: the decoder was trained at velocities 0.4/0.7/1.0 only, so its input is clamped to\n"
    ";; [0.4, 1] (timbre as trained) and a plain gain v/0.4 carries the level below 0.4 (VILLAIN's slope there).\n"
    "(def vel-gain (event-hold (min 1 (/ (clip velocity 0 1) 0.4)) hit))\n"
    "(def voice-out (* (+ shaped carry) level vel-gain))")
open(os.path.join(dest, "dsp.lisp"), "w").write(dsp)
print(f"{dest}: dsp.lisp {len(dsp) / 1024:.0f} KB, warp table {rows}x{NK}")
