"""E7 step 4: splice E5's W2 wire layer into a copy of the E2 instrument.
 e7/Latent Snare/                 = e2/Latent Snare dsp.lisp + SVF macros + wire_block(2), weights_wires (cols 355-359)
 e7/variants/Latent Snare rebal/  = same dsp, weights_wires_rebal (also band_amp cols)
 e7/variants/Latent Snare headtap/= main + out 3 = gated head (parity research only)
W1/b1 keep E2's export transform (PCA knobs); W3/b3 are trainer-space = export-space (export only
rotates layer 1), so the refit columns are copied straight in."""
import json, os, shutil, sys
import numpy as np
import os, sys  # noqa: E401
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import modal_ad as MAD  # noqa: E402
HERE = MAD.stage("e7"); R = MAD.ROOT
MAD.use("e5"); sys.argv = sys.argv[:1]
from wire_splice import wire_block, SVF_MACROS  # noqa: E402  (read-only import of E5's splice)
SRC = os.path.join(R, "e2", "Latent Snare")



def splice(src, headtap=False):
    a = "(def hit (onset-of trigger))"; assert src.count(a) == 1
    src = src.replace(a, SVF_MACROS + "\n" + a)
    d = "(def dry (+ head noise-out))"; assert src.count(d) == 1
    src = src.replace(d, wire_block(2) + "\n(def dry (+ head noise-out wire-out))")
    src = src.replace(";; Latent Modal Snare (E3 realtime prototype) -- GENERATED by gen_dsp.py, do not edit.",
                      ";; Latent Modal Snare + E5 W2 snare wires (E7) -- GENERATED: e2 gen_dsp.py output spliced by scripts/e7/build_instrument.py\n"
                      ";; (scripts/e5/wire_splice.py wire_block(2)); wire knobs = decoder outputs 355-359, drive/hz/t60 fixed 1.2/620/1.0.")
    if headtap:
        o = '(out (voice-amp 0 voice-out voice-out) 2 @name amp @amp true)'; assert src.count(o) == 1
        src = src.replace(o, o + "\n(out head 3 @name head_tap)\n(out wire-out 4 @name wire_tap)")
    return src


def build(dest, weights, headtap=False, name="Research/Latent Snare W2"):
    if os.path.exists(dest): shutil.rmtree(dest)
    os.makedirs(dest)
    for f in ("w1.json", "b1.json", "w2.json", "b2.json", "codes_std.json", "decoder_layout.json", "ui.lisp"):
        shutil.copy(os.path.join(SRC, f), dest)
    ij = json.load(open(os.path.join(SRC, "instrument.json"))); ij["releases"]["1"]["name"] = name
    json.dump(ij, open(os.path.join(dest, "instrument.json"), "w"), indent=2)
    open(os.path.join(dest, "dsp.lisp"), "w").write(splice(open(os.path.join(SRC, "dsp.lisp")).read(), headtap))
    w = json.load(open(weights))
    W3 = np.array(json.load(open(os.path.join(SRC, "w3.json")))["data"]).reshape(128, 360)
    b3 = np.array(json.load(open(os.path.join(SRC, "b3.json")))["data"]).reshape(1, 360)
    nW = np.array(w["l3"]["W"]["data"]).reshape(128, 360); nb = np.array(w["l3"]["b"]["data"]).reshape(1, 360)
    changed = np.where(np.any(np.abs(nW - W3) > 1e-6, 0) | (np.abs(nb - b3)[0] > 1e-6))[0]
    W3 = nW; b3 = nb  # trainer l3 == export l3 (checked to 5e-9)
    for f, a in (("w3.json", W3), ("b3.json", b3)):
        json.dump({"shape": list(a.shape), "data": [round(float(x), 8) for x in a.reshape(-1)]}, open(os.path.join(dest, f), "w"))
    print(dest, "changed l3 columns:", changed.tolist())


if __name__ == "__main__":
    build(os.path.join(HERE, "Latent Snare"), os.path.join(HERE, "weights_wires.json"))
    build(os.path.join(HERE, "variants", "Latent Snare rebal"), os.path.join(HERE, "weights_wires_rebal.json"), name="Research/Latent Snare W2 rebal")
    build(os.path.join(HERE, "variants", "Latent Snare headtap"), os.path.join(HERE, "weights_wires.json"), headtap=True, name="Research/Latent Snare W2 headtap")
